package store

import (
	"context"
	"time"

	"github.com/knadh/listmonk/models"
)

// CampaignRef addresses one campaign. Precedence, as in get-campaign:
// ID if > 0, else ArchiveSlug if set, else UUID.
type CampaignRef struct {
	ID          int
	UUID        string
	ArchiveSlug string
}

// TemplateKind chooses which template body Get returns in TemplateBody.
type TemplateKind string

const (
	TemplateCampaign TemplateKind = "default" // the campaign's own template
	TemplateArchive  TemplateKind = "archive" // the public archive template
)

// CampaignFilter selects campaigns for listing and bulk deletion.
type CampaignFilter struct {
	// IDs, if set, selects exactly these campaigns and the fields below
	// except Scope are ignored (bulk delete by selection).
	IDs      []int
	Search   string // name / subject search
	Statuses []string
	Tags     []string
	Type     string // "regular" / "optin"; empty = any
	Scope    ListScope
}

// CampaignProgress is the manager's checkpoint for a campaign it is
// sending.
type CampaignProgress struct {
	ID        int
	Sent      int
	LastSubID int
}

// ArchiveSettings is a campaign's public archive configuration.
type ArchiveSettings struct {
	Enabled    bool
	Slug       string
	TemplateID int
	Meta       models.JSON
}

// CampaignStore is campaigns and their sending state. Campaigns returned
// by Query, Get, Create and Update have Tags non-nil and their stats
// (views, clicks, bounces, lists, media) loaded; GetForPreview, Archived
// and Next return the row only, as upstream.
type CampaignStore interface {
	// Query returns one page of campaigns and the total. Sort.Field is
	// one of name, status, created_at, updated_at, started_at, send_at.
	Query(ctx context.Context, f CampaignFilter, s Sort, p Page) (models.Campaigns, int, error)

	// Get returns one campaign with the chosen template body, or
	// ErrNotFound.
	Get(ctx context.Context, ref CampaignRef, tpl TemplateKind) (models.Campaign, error)

	// GetForPreview returns a campaign with a template body: tplID's if
	// > 0, else the campaign's own. ErrNotFound if missing.
	GetForPreview(ctx context.Context, id, tplID int) (models.Campaign, error)

	// Archived returns one page of publicly archived campaigns, optionally
	// only those sent to listUUID, with archive template bodies.
	Archived(ctx context.Context, listUUID string, p Page) (models.Campaigns, int, error)

	// Create inserts a campaign on the given lists, with media attached,
	// and returns it. UUID generated by the store. With no TemplateID the
	// default template is used; a visual template's body is copied in.
	// *ConflictError{Field: "archive_slug"} on a duplicate slug.
	Create(ctx context.Context, c models.Campaign, listIDs, mediaIDs []int) (models.Campaign, error)

	// Update replaces a campaign's editable fields, lists and media and
	// returns it.
	Update(ctx context.Context, id int, c models.Campaign, listIDs, mediaIDs []int) (models.Campaign, error)

	// SetStatus sets a campaign's status; ErrNotFound if missing.
	// Transition rules stay in core (read, check, write, as today).
	// Later improvement: a compare-and-set variant so two requests can't
	// both act on the same old status.
	SetStatus(ctx context.Context, id int, status string) error

	// SetArchive updates the public archive settings;
	// *ConflictError{Field: "archive_slug"} on a duplicate slug.
	SetArchive(ctx context.Context, id int, a ArchiveSettings) error

	// Delete deletes one campaign; ErrNotFound if missing.
	Delete(ctx context.Context, id int) error

	// DeleteMany deletes the campaigns matching f; returns how many.
	DeleteMany(ctx context.Context, f CampaignFilter) (int, error)

	// HasLists reports whether the campaign targets any of listIDs.
	HasLists(ctx context.Context, id int, listIDs []int) (bool, error)

	// RunningStats returns send progress for running campaigns in scope.
	RunningStats(ctx context.Context, scope ListScope) ([]models.CampaignStats, error)

	// --- Sending (used by internal/manager through cmd/manager_store.go) ---

	// Next, atomically: adds the given sent counts and checkpoints to the
	// campaigns being sent; selects campaigns that are running, or
	// scheduled with send_at reached, excluding the in-progress IDs; sets
	// those to running and records to_send, max_subscriber_id and
	// started_at; returns them with template body and media IDs.
	Next(ctx context.Context, inProgress []CampaignProgress) ([]*models.Campaign, error)

	// NextSubscribers returns up to limit recipients of a running
	// campaign with id > afterID and <= max_subscriber_id, in id order:
	// not blocklisted; on double opt-in lists only confirmed (optin
	// campaigns: only unconfirmed); on single opt-in lists any status but
	// unsubscribed. nil when done.
	NextSubscribers(ctx context.Context, campID, afterID, limit int) ([]models.Subscriber, error)

	// SetCounts updates a campaign's to_send, sent and last subscriber ID.
	SetCounts(ctx context.Context, id, toSend, sent, lastSubID int) error
}

// TrackingStore is links, views and clicks.
type TrackingStore interface {
	// CreateLink returns the UUID of a tracked link for url, creating it
	// if it doesn't exist (idempotent).
	CreateLink(ctx context.Context, url string) (string, error)

	// LinkURL returns a link's URL without recording a click;
	// ErrNotFound if unknown.
	LinkURL(ctx context.Context, linkUUID string) (string, error)

	// RegisterView records a campaign view. subUUID may be empty
	// (individual tracking off). ErrNotFound if the campaign is unknown.
	RegisterView(ctx context.Context, campUUID, subUUID string) error

	// RegisterClick records a link click and returns the link's URL.
	// ErrNotFound if the link is unknown.
	RegisterClick(ctx context.Context, linkUUID, campUUID, subUUID string) (string, error)

	// Export views / clicks since a time, one page at a time.
	ExportViews(ctx context.Context, since time.Time, p Page) ([]models.CampaignViewExport, error)
	ExportClicks(ctx context.Context, since time.Time, p Page) ([]models.CampaignClickExport, error)

	// Retention: delete views / clicks older than a time.
	DeleteViewsBefore(ctx context.Context, before time.Time) (int, error)
	DeleteClicksBefore(ctx context.Context, before time.Time) (int, error)
}
