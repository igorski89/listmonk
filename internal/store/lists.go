package store

import (
	"context"

	"github.com/knadh/listmonk/models"
)

// ListRef addresses one list by ID (if > 0) or UUID.
type ListRef struct {
	ID   int
	UUID string
}

// ListFilter selects lists. Zero values mean "no condition".
type ListFilter struct {
	// IDs, if set, selects exactly these lists; the fields below except
	// Scope are then ignored (bulk delete by selection).
	IDs    []int
	Search string // name search
	Type   string // "public" / "private"
	Optin  string // "single" / "double"
	Status string // "active" / "archived"
	Tags   []string
	Scope  ListScope
}

// ListStore is mailing lists. Returned lists carry their subscriber
// counts (total and per subscription status) where the query lists them;
// on Postgres these come from the cached aggregates (see StatsStore).
type ListStore interface {
	// Get returns one list within scope, or ErrNotFound.
	Get(ctx context.Context, ref ListRef, scope ListScope) (models.List, error)

	// All returns every list in scope with the given type and status
	// (empty = any), ordered by ID, without pagination. For dropdowns.
	All(ctx context.Context, typ, status string, scope ListScope) ([]models.List, error)

	// Query returns one page of lists and the total. Sort.Field is one of
	// name, status, created_at, updated_at, subscriber_count.
	Query(ctx context.Context, f ListFilter, s Sort, p Page) ([]models.List, int, error)

	// ByOptin returns those of the given lists that have the opt-in type.
	ByOptin(ctx context.Context, ids []int, optin string) ([]models.List, error)

	// Types returns the type ("public"/"private") of each given list,
	// keyed by the ID or UUID it was asked for.
	Types(ctx context.Context, ids []int, uuids []string) (map[any]string, error)

	// Create inserts a list (UUID generated by the store) and returns it.
	Create(ctx context.Context, l models.List) (models.List, error)

	// Update changes a list and returns it: empty name, type, optin,
	// status and description keep their value; tags are always replaced.
	// Also updates the list name stored on its campaigns. ErrNotFound if
	// missing.
	Update(ctx context.Context, id int, l models.List) (models.List, error)

	// DeleteMany deletes the lists matching f; returns how many.
	DeleteMany(ctx context.Context, f ListFilter) (int, error)

	// Touch sets updated_at on lists (after an import).
	Touch(ctx context.Context, ids []int) error
}
