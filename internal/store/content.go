package store

import (
	"context"
	"encoding/json"

	"github.com/knadh/listmonk/internal/media"
	"github.com/knadh/listmonk/models"
	null "gopkg.in/volatiletech/null.v6"
)

// TemplateInput is the editable part of a template.
type TemplateInput struct {
	Name       string
	Type       string // campaign, campaign_visual, tx; fixed after create
	Subject    string // tx templates only
	Body       string
	BodySource null.String // visual editor source, campaign_visual only
}

// TemplateStore is e-mail templates.
type TemplateStore interface {
	// Query returns templates of a type (empty = any) matching a name
	// search. noBody leaves Body empty. Sort.Field is one of name, type,
	// created_at, updated_at.
	Query(ctx context.Context, search, typ string, noBody bool, s Sort) ([]models.Template, error)

	// Get returns one template, or ErrNotFound.
	Get(ctx context.Context, id int, noBody bool) (models.Template, error)

	Create(ctx context.Context, t TemplateInput) (models.Template, error)

	// Update changes name, subject, body and body source; ErrNotFound if
	// missing.
	Update(ctx context.Context, id int, t TemplateInput) (models.Template, error)

	// SetDefault makes a template of type "campaign" the default one.
	// (Upstream clears the old default even if id isn't such a template;
	// stores should keep that until the conformance suite decides.)
	SetDefault(ctx context.Context, id int) error

	// Delete deletes a template unless it is the default or the last one
	// (then ErrNotFound); campaigns using it switch to the default
	// template.
	Delete(ctx context.Context, id int) error
}

// MediaInput is a new media item's metadata. The file itself lives in a
// media.Store (filesystem or S3); this store only keeps the record.
type MediaInput struct {
	Filename    string
	Thumb       string
	ContentType string
	Provider    string
	Meta        models.JSON
	Tags        []string
}

// MediaRef addresses one media item by ID (if > 0), UUID or filename.
type MediaRef struct {
	ID       int
	UUID     string
	Filename string
}

// MediaStore is media records. URLs are filled in by the caller from the
// file provider, not here.
type MediaStore interface {
	// Query returns one page of a provider's media, newest first, and the
	// total. search (case-insensitive substring, empty = any) matches the
	// filename or any tag; the item must have all the given tags.
	Query(ctx context.Context, provider, search string, tags []string, p Page) ([]media.Media, int, error)

	// Get returns one item, or ErrNotFound.
	Get(ctx context.Context, ref MediaRef) (media.Media, error)

	// Tags returns a provider's tags with usage counts.
	Tags(ctx context.Context, provider string) ([]media.Tag, error)

	// Insert records an uploaded file (UUID generated by the store).
	Insert(ctx context.Context, m MediaInput) (media.Media, error)

	// SetTags replaces an item's tags; ErrNotFound if missing.
	SetTags(ctx context.Context, id int, tags []string) (media.Media, error)

	// Delete deletes the record and returns its filename, so the caller
	// can delete the file; ErrNotFound if missing.
	Delete(ctx context.Context, id int) (string, error)
}

// SettingsStore is the key/value settings table. Values are JSON; the
// app decodes them into models.Settings.
type SettingsStore interface {
	// All returns every setting as one JSON object {key: value}.
	All(ctx context.Context) (json.RawMessage, error)

	// Update writes every key of a JSON object {key: value}, atomically.
	Update(ctx context.Context, settings json.RawMessage) error

	// Set writes one key.
	Set(ctx context.Context, key string, value json.RawMessage) error
}
